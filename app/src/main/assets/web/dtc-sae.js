/** Descrição do perfil, a genérica da norma ou o grupo; '' se nada se aplica. */
function dtcDescribe(code, profileDescriptions) {
  const c = String(code || '').toUpperCase();
  const own = (profileDescriptions || {})[c];
  if (own) return { text: own, source: 'perfil' };
  if (DTC_SAE[c]) return { text: DTC_SAE[c], source: 'norma' };
  const kind = { P: 'motor e transmissão', C: 'chassi', B: 'carroceria', U: 'rede de comunicação' }[c[0]];
  if (!kind) return { text: '', source: '' };
  // 2º caractere 1 (e P30–P33) é código do fabricante: o significado muda de marca para marca.
  if (c[1] === '1' || (c[0] === 'P' && c[1] === '3' && '0123'.includes(c[2]))) return { text: `Código do fabricante (${kind})`, source: 'grupo' };
  const group = c[0] === 'P' && c[1] === '0' ? DTC_GROUPS[c.slice(0, 3)] : null;
  return { text: group ? `${group} (código genérico)` : `Código genérico de ${kind}`, source: 'grupo' };
}
